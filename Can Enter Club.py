# Write a function to determine if a person can enter a club.
# Instructions
# The club only allows people who are 21 years old or older.
# Return True if the person can enter the club. Otherwise, return False if they cannot enter the club.


def can_enter_club(age):
    return True if age >= 21 else False

    if age >= 21:
        return True
    else:
        return False
